export function getSupportCategory(id: string): SupportCategory | undefined {
  return SUPPORT_CATEGORIES.find((c) => c.id === id);
}

export function getSupportArticle(
  categoryId: string,
  articleId: string,
): SupportArticle | undefined {
  const category = getSupportCategory(categoryId);
  return category?.articles.find((a) => a.id === articleId);
}
